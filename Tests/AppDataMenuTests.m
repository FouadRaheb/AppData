    assert(class_isMetaClass(cls));
    Method m = class_getInstanceMethod(cls, sel);
    assert(m && *original == method_getImplementation(m));
    *original = method_getImplementation(m);
    class_replaceMethod(cls, sel, replacement, method_getTypeEncoding(m));
    installCalls++;
}

